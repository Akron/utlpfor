// Generator for per-bitwidth specialized SIMD pack/unpack functions.
// Generates SSE2 (Uint32x4, 4 groups), AVX2 (Uint32x8, 2 groups),
// and AVX-512 (Uint32x16, 1 group) per-bitwidth specialized functions.
//
// Key optimizations:
//   - Unpack: source super-words are pre-loaded into local variables grouped
//     by wordIdx, and lo/hi halves (AVX2) or quarter groups (SSE2) are
//     processed separately to minimize live register count.
//   - Pack: uses accumulator registers per destination word instead of
//     load-OR-store pattern. Each destination word is only stored once,
//     eliminating redundant memory round-trips.
//
// Run: go run ./internal/gen | gofmt > simd_spec_amd64.go
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"
)

type bitLayout struct {
	wordIdx int
	shift   int
	spans   bool
}

func computeLayout(bw int) [8]bitLayout {
	var out [8]bitLayout
	for v := range 8 {
		bp := v * bw
		out[v] = bitLayout{
			wordIdx: bp / 32,
			shift:   bp % 32,
			spans:   (bp%32)+bw > 32,
		}
	}
	return out
}

type wordGroup struct {
	wordIdx  int
	values   []int
	needNext bool
}

func groupByWord(layout [8]bitLayout) []wordGroup {
	m := map[int]*wordGroup{}
	for v := range 8 {
		wi := layout[v].wordIdx
		g, ok := m[wi]
		if !ok {
			g = &wordGroup{wordIdx: wi}
			m[wi] = g
		}
		g.values = append(g.values, v)
		if layout[v].spans {
			g.needNext = true
		}
	}
	var groups []wordGroup
	for _, g := range m {
		groups = append(groups, *g)
	}
	sort.Slice(groups, func(i, j int) bool { return groups[i].wordIdx < groups[j].wordIdx })
	return groups
}

var stepBWs = []int{4, 8, 12, 16, 20, 24, 28, 32}

func main() {
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("// Code generated by internal/gen. DO NOT EDIT.\n\n")
	w("//go:build goexperiment.simd && amd64\n\n")
	w("package utlpfor\n\n")
	w("import (\n")
	w("\t\"simd/archsimd\"\n")
	w("\t\"unsafe\"\n")
	w(")\n\n")

	w("// --- AVX2 per-bitwidth specialized functions (Uint32x8, 2 groups) ---\n\n")
	for _, bw := range stepBWs {
		generateUnpackAVX2(&b, bw)
		w("\n")
		generatePackAVX2(&b, bw)
		w("\n")
	}

	w("// --- SSE2 per-bitwidth specialized functions (Uint32x4, 4 groups) ---\n\n")
	for _, bw := range stepBWs {
		generateUnpackSSE2(&b, bw)
		w("\n")
		generatePackSSE2(&b, bw)
		w("\n")
	}

	w("// --- AVX-512 per-bitwidth specialized functions (Uint32x16, 1 group) ---\n\n")
	for _, bw := range stepBWs {
		generateUnpackAVX512(&b, bw)
		w("\n")
		generatePackAVX512(&b, bw)
		w("\n")
	}

	os.Stdout.WriteString(b.String())
}

// AVX2 helpers (Uint32x8, 2 halves per super-word).

func ld8(ptrVar string, off int) string {
	return fmt.Sprintf("archsimd.LoadUint32x8((*[8]uint32)(unsafe.Add(%s, %d)))", ptrVar, off)
}

func st8(ptrVar string, off int) string {
	return fmt.Sprintf(".Store((*[8]uint32)(unsafe.Add(%s, %d)))", ptrVar, off)
}

// generateUnpackAVX2 generates an unpack function that processes
// the lo half (lanes 0-7) first, then the hi half (lanes 8-15)
// to minimize live YMM register count.
func generateUnpackAVX2(b *strings.Builder, bw int) {
	w := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }
	layout := computeLayout(bw)

	mask := uint32((1 << bw) - 1)
	if bw == 32 {
		mask = 0xFFFFFFFF
	}

	w("// unpackAVX2BW%d unpacks 128 uint32 values at bitwidth %d using AVX2.\n", bw, bw)
	w("func unpackAVX2BW%d(dst *uint32, payload *byte) {\n", bw)
	w("\tp := unsafe.Pointer(payload)\n")
	w("\td := unsafe.Pointer(dst)\n")

	if bw == 32 {
		for v := range 8 {
			for g := range 2 {
				pOff := v*64 + g*32
				dOff := (v*16 + g*8) * 4
				w("\t%s%s\n", ld8("p", pOff), st8("d", dOff))
			}
		}
		w("}\n")
		return
	}

	w("\tmask := archsimd.BroadcastUint32x8(0x%X)\n", mask)

	groups := groupByWord(layout)

	for _, grp := range groups {
		wName := fmt.Sprintf("w%dlo", grp.wordIdx)
		w("\t%s := %s\n", wName, ld8("p", grp.wordIdx*64))

		var nName string
		if grp.needNext {
			nName = fmt.Sprintf("w%dnlo", grp.wordIdx)
			w("\t%s := %s\n", nName, ld8("p", (grp.wordIdx+1)*64))
		}

		for _, v := range grp.values {
			l := layout[v]
			dOff := (v * 16) * 4
			if !l.spans {
				if l.shift == 0 {
					w("\t%s.And(mask)%s\n", wName, st8("d", dOff))
				} else {
					w("\t%s.ShiftAllRight(%d).And(mask)%s\n", wName, l.shift, st8("d", dOff))
				}
			} else {
				leftShift := 32 - l.shift
				w("\t%s.ShiftAllRight(%d).And(mask).Or(%s.ShiftAllLeft(%d).And(mask))%s\n",
					wName, l.shift, nName, leftShift, st8("d", dOff))
			}
		}
	}

	for _, grp := range groups {
		wName := fmt.Sprintf("w%dhi", grp.wordIdx)
		w("\t%s := %s\n", wName, ld8("p", grp.wordIdx*64+32))

		var nName string
		if grp.needNext {
			nName = fmt.Sprintf("w%dnhi", grp.wordIdx)
			w("\t%s := %s\n", nName, ld8("p", (grp.wordIdx+1)*64+32))
		}

		for _, v := range grp.values {
			l := layout[v]
			dOff := (v*16 + 8) * 4
			if !l.spans {
				if l.shift == 0 {
					w("\t%s.And(mask)%s\n", wName, st8("d", dOff))
				} else {
					w("\t%s.ShiftAllRight(%d).And(mask)%s\n", wName, l.shift, st8("d", dOff))
				}
			} else {
				leftShift := 32 - l.shift
				w("\t%s.ShiftAllRight(%d).And(mask).Or(%s.ShiftAllLeft(%d).And(mask))%s\n",
					wName, l.shift, nName, leftShift, st8("d", dOff))
			}
		}
	}

	w("}\n")
}

// generatePackAVX2 generates a pack function using accumulator registers
// per destination word. Each destination super-word half is written only
// once, eliminating redundant load-OR-store memory round-trips.
func generatePackAVX2(b *strings.Builder, bw int) {
	w := func(format string, args ...any) { fmt.Fprintf(b, format, args...) }
	layout := computeLayout(bw)

	mask := uint32((1 << bw) - 1)
	if bw == 32 {
		mask = 0xFFFFFFFF
	}

	w("// packAVX2BW%d packs 128 uint32 values at bitwidth %d using AVX2.\n", bw, bw)
	w("func packAVX2BW%d(dst *byte, values *uint32) {\n", bw)
	w("\tp := unsafe.Pointer(values)\n")
	w("\td := unsafe.Pointer(dst)\n")

	if bw == 32 {
		for v := range 8 {
			for g := range 2 {
				pOff := (v*16 + g*8) * 4
				dOff := v*64 + g*32
				w("\t%s%s\n", ld8("p", pOff), st8("d", dOff))
			}
		}
		w("}\n")
		return
	}

	w("\tmask := archsimd.BroadcastUint32x8(0x%X)\n", mask)

	groups := groupByWord(layout)

	for _, halfOff := range []int{0, 32} {
		halfLabel := "lo"
		if halfOff == 32 {
			halfLabel = "hi"
		}
		valGroupOff := 0
		if halfOff == 32 {
			valGroupOff = 8
		}

		for gi, grp := range groups {
			accName := fmt.Sprintf("acc%d%s", grp.wordIdx, halfLabel)
			dOff := grp.wordIdx*64 + halfOff

			type contribution struct {
				valueIdx   int
				shift      int
				isHighPart bool
			}
			var contribs []contribution

			if gi > 0 {
				prevGrp := groups[gi-1]
				for _, v := range prevGrp.values {
					if layout[v].spans {
						rightShift := 32 - layout[v].shift
						contribs = append(contribs, contribution{v, rightShift, true})
					}
				}
			}

			for _, v := range grp.values {
				contribs = append(contribs, contribution{v, layout[v].shift, false})
			}

			if len(contribs) == 0 {
				continue
			}

			for ci, c := range contribs {
				pOff := (c.valueIdx*16 + valGroupOff) * 4
				valExpr := fmt.Sprintf("%s.And(mask)", ld8("p", pOff))

				if c.isHighPart {
					valExpr = fmt.Sprintf("%s.ShiftAllRight(%d)", valExpr, c.shift)
				} else if c.shift > 0 {
					valExpr = fmt.Sprintf("%s.ShiftAllLeft(%d)", valExpr, c.shift)
				}

				if ci == 0 {
					w("\t%s := %s\n", accName, valExpr)
				} else {
					w("\t%s = %s.Or(%s)\n", accName, accName, valExpr)
				}
			}

			w("\t%s%s\n", accName, st8("d", dOff))
		}

		lastGrp := groups[len(groups)-1]
		for _, v := range lastGrp.values {
			if layout[v].spans {
				nextWordIdx := lastGrp.wordIdx + 1
				dOff := nextWordIdx*64 + halfOff
				pOff := (v*16 + valGroupOff) * 4
				rightShift := 32 - layout[v].shift
				accName := fmt.Sprintf("acc%d%s", nextWordIdx, halfLabel)
				w("\t%s := %s.And(mask).ShiftAllRight(%d)\n", accName, ld8("p", pOff), rightShift)
				w("\t%s%s\n", accName, st8("d", dOff))
			}
		}
	}

	w("}\n")
}

