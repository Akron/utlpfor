		for _, v := range lastGrp.values {
			if layout[v].spans {
				nextWordIdx := lastGrp.wordIdx + 1
				dOff := nextWordIdx*64 + g*16
				pOff := (v*16 + valOff) * 4
				rightShift := 32 - layout[v].shift
				accName := fmt.Sprintf("acc%dg%d", nextWordIdx, g)
				w("\t%s := %s.And(mask).ShiftAllRight(%d)\n", accName, ld4("p", pOff), rightShift)
				w("\t%s%s\n", accName, st4("d", dOff))
			}
		}
